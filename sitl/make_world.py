#!/usr/bin/env python3
"""Write a Gazebo Classic world that shows the envelope.

    make_world.py <envelope> <out.world>

PX4's empty world, plus the fence as translucent walls and each exclusion
zone as a translucent block, and a GUI camera that follows the vehicle. The
walls are visual only, with no collision: the unguarded run has to be able to
fly through them, because that is what it would do to the real boundary.
"""

import math
import sys

sys.path.insert(0, __import__("os").path.dirname(__file__))
from analyze import load_envelope  # noqa: E402

WALL_HEIGHT = 40.0
WALL_THICKNESS = 0.6


def box(name, x, y, z, yaw, sx, sy, sz, rgba, transparency):
    r, g, b, a = rgba
    return f"""
    <model name="{name}">
      <static>true</static>
      <pose>{x:.3f} {y:.3f} {z:.3f} 0 0 {yaw:.5f}</pose>
      <link name="link">
        <visual name="visual">
          <cast_shadows>false</cast_shadows>
          <transparency>{transparency}</transparency>
          <geometry><box><size>{sx:.3f} {sy:.3f} {sz:.3f}</size></box></geometry>
          <material>
            <ambient>{r} {g} {b} {a}</ambient>
            <diffuse>{r} {g} {b} {a}</diffuse>
            <emissive>{r * 0.4:.2f} {g * 0.4:.2f} {b * 0.4:.2f} 1</emissive>
          </material>
        </visual>
      </link>
    </model>"""


def camera_pose(fence):
    """Aim at the middle of the fence's bounding box from the south-west."""
    xs, ys = [p[0] for p in fence], [p[1] for p in fence]
    cx, cy = (min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2
    back = 0.78 * max(max(xs) - min(xs), max(ys) - min(ys))
    height = 0.80 * max(max(xs) - min(xs), max(ys) - min(ys))
    px, py = cx - back, cy - back
    pitch = math.atan2(height, math.hypot(cx - px, cy - py))
    yaw = math.atan2(cy - py, cx - px)
    return f"{px:.1f} {py:.1f} {height:.1f} 0 {pitch:.3f} {yaw:.3f}"


def main():
    env = load_envelope(sys.argv[1])
    models = []
    fence = env["fence"]
    for i, (a, b) in enumerate(zip(fence, fence[1:] + fence[:1])):
        length = math.dist(a, b) + WALL_THICKNESS
        yaw = math.atan2(b[1] - a[1], b[0] - a[0])
        models.append(box(f"fence_{i}", (a[0] + b[0]) / 2, (a[1] + b[1]) / 2, WALL_HEIGHT / 2,
                          yaw, length, WALL_THICKNESS, WALL_HEIGHT, (1.0, 0.75, 0.1, 1), 0.5))
    for name, poly in env["zones"].items():
        xs, ys = [p[0] for p in poly], [p[1] for p in poly]
        models.append(box(f"zone_{name}", (min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2,
                          WALL_HEIGHT / 2, 0, max(xs) - min(xs), max(ys) - min(ys), WALL_HEIGHT,
                          (0.85, 0.15, 0.15, 1), 0.0))

    world = f"""<?xml version="1.0" ?>
<!-- Generated by sitl/make_world.py from the envelope. Do not edit. -->
<sdf version="1.6">
  <world name="default">
    <include><uri>model://sun</uri></include>
    <!-- PX4's ground plane is 100 m across; the field is 300. -->
    <model name="field_ground">
      <static>true</static>
      <link name="link">
        <collision name="collision">
          <geometry><plane><normal>0 0 1</normal><size>3000 3000</size></plane></geometry>
        </collision>
        <visual name="visual">
          <cast_shadows>false</cast_shadows>
          <geometry><plane><normal>0 0 1</normal><size>3000 3000</size></plane></geometry>
          <material><ambient>0.45 0.58 0.38 1</ambient><diffuse>0.45 0.58 0.38 1</diffuse></material>
        </visual>
      </link>
    </model>
    <scene>
      <sky><clouds><speed>0</speed></clouds></sky>
      <shadows>false</shadows>
      <grid>false</grid>
      <ambient>0.6 0.6 0.6 1</ambient>
      <background>0.75 0.85 0.95 1</background>
    </scene>
    <gui fullscreen="0">
      <camera name="user_camera">
        <!-- A fixed wide shot of the whole field from the south-west. The
             vehicle is too small to see at this range on its own; record mode
             gives it a marker (see run.sh). -->
        <pose>{camera_pose(fence)}</pose>
      </camera>
    </gui>
    <gravity>0 0 -9.8066</gravity>
    <magnetic_field>6.0e-6 2.3e-5 -4.2e-5</magnetic_field>
    <physics name="default_physics" default="0" type="ode">
      <ode>
        <solver><type>quick</type><iters>10</iters><sor>1.3</sor>
          <use_dynamic_moi_rescaling>0</use_dynamic_moi_rescaling></solver>
        <constraints><cfm>0</cfm><erp>0.2</erp>
          <contact_max_correcting_vel>100</contact_max_correcting_vel>
          <contact_surface_layer>0.001</contact_surface_layer></constraints>
      </ode>
      <max_step_size>0.004</max_step_size>
      <real_time_factor>1</real_time_factor>
      <real_time_update_rate>250</real_time_update_rate>
    </physics>{''.join(models)}
  </world>
</sdf>
"""
    with open(sys.argv[2], "w") as f:
        f.write(world)


if __name__ == "__main__":
    main()
